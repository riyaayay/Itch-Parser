from __future__ import annotations
import argparse
import hashlib
import pathlib
import struct
import sys
from collections import Counter
from typing import List, Tuple, Dict, Optional


FIXED_SLOTS = [
    b"AAPL    ",
    b"SPY     ",
    b"MSFT    ",
]

DEFAULT_SLOTS_3_TO_7 = [
    b"QQQ     ",
    b"NVDA    ",
    b"TSLA    ",
    b"AMZN    ",
    b"META    ",
]


def sha256_of_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def run_census(
    itch_file: Optional[pathlib.Path]
) -> Tuple[List[bytes], Dict[bytes, int], str, str]:
    """
    Counts Add Order (0x41) and Add Order with MPID (0x46) per stock.
    Returns (selected_8_symbols, counts_dict, filename_str, sha256_str).
    """
    counts: Counter[bytes] = Counter()
    filename_str = "DEFAULT_SYNTHETIC"
    sha256_str = "N/A"

    if itch_file and itch_file.exists() and itch_file.stat().st_size > 0:
        filename_str = str(itch_file)
        sha256_str = sha256_of_file(itch_file)
        with open(itch_file, "rb") as f:
            while True:
                prefix = f.read(2)
                if len(prefix) < 2:
                    break
                pkt_len = struct.unpack(">H", prefix)[0]
                if pkt_len == 0:
                    continue
                payload = f.read(pkt_len)
                if len(payload) < pkt_len:
                    break
                mtype = payload[0]
                if mtype in (0x41, 0x46):  # 'A', 'F'
                    # Stock is at payload offset 24..31 (8 bytes)
                    if len(payload) >= 32:
                        stock = payload[24:32]
                        counts[stock] += 1
    else:
        # Default fallback census
        for s in FIXED_SLOTS:
            counts[s] = 1000
        for i, s in enumerate(DEFAULT_SLOTS_3_TO_7):
            counts[s] = 500 - i * 50

    # Ensure fixed slots 0..2
    selected: List[bytes] = list(FIXED_SLOTS)

    # Filter out fixed slots from census candidates
    candidate_counts = {
        s: c for s, c in counts.items() if s not in FIXED_SLOTS and s != b"\x00" * 8
    }

    # Sort candidates by (-count, stock_bytes)
    sorted_candidates = sorted(
        candidate_counts.items(),
        key=lambda item: (-item[1], item[0])
    )

    top5 = [s for s, _ in sorted_candidates[:5]]
    # Pad with defaults if fewer than 5 candidates
    for d in DEFAULT_SLOTS_3_TO_7:
        if len(top5) >= 5:
            break
        if d not in selected and d not in top5:
            top5.append(d)

    selected.extend(top5)
    return selected[:8], dict(counts), filename_str, sha256_str


def write_symbols_header(selected: List[bytes], out_header: pathlib.Path):
    """Write rtl/t2t_symbols.vh according to Section 8.1."""
    out_header.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// =============================================================================",
        "// File        : rtl/t2t_symbols.vh",
        "// Spec Section: 8.1 & 11.2",
        "// Description : Default 8-byte space-padded ASCII tickers for slots 0..7.",
        "//               Generated by tools/symbol_census.py (Section 8.1).",
        "// Copyright (c) 2026 Riya Rathod. Licensed under the MIT License.",
        "// =============================================================================",
        "",
        "`ifndef T2T_SYMBOLS_VH",
        "`define T2T_SYMBOLS_VH",
        "",
        "// Character 0 sits in bits [63:56], padded with 0x20 (' ') on the right",
    ]
    for i, sym in enumerate(selected):
        sym_8b = sym[:8].ljust(8, b" ")
        hex_val = sym_8b.hex().upper()
        # format as 64'hXXXX_XXXX_XXXX_XXXX
        formatted_hex = f"{hex_val[0:4]}_{hex_val[4:8]}_{hex_val[8:12]}_{hex_val[12:16]}"
        sym_str = sym_8b.decode("ascii", errors="replace")
        lines.append(f'`define T2T_SYM_SLOT{i} 64\'h{formatted_hex} // "{sym_str}"')

    lines.append("")
    lines.append("`endif // T2T_SYMBOLS_VH\n")

    with open(out_header, "w", encoding="ascii") as f:
        f.write("\n".join(lines))


def write_census_report(
    selected: List[bytes],
    counts: Dict[bytes, int],
    filename_str: str,
    sha256_str: str,
    out_report: pathlib.Path
):
    out_report.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "=============================================================================",
        "NASDAQ ITCH 5.0 Symbol Census Report (Section 8.1)",
        "=============================================================================",
        f"Input Source File : {filename_str}",
        f"SHA-256 Digest    : {sha256_str}",
        f"Total Unique Tickers Tracked in Census: {len(counts)}",
        "",
        "--- Selected 8 Symbol Slots (rtl/t2t_symbols.vh) ---",
        "Slot | Ticker   | ASCII Hex Value    | ITCH Add Count | Selection Rule",
        "-----+----------+--------------------+----------------+------------------------",
    ]
    for i, s in enumerate(selected):
        s_str = s.decode("ascii", errors="replace")
        rule_str = "Fixed (Slot 0..2)" if i < 3 else "Top Add Volume (Census)"
        cnt = counts.get(s, 0)
        lines.append(f"{i:4d} | {s_str:8s} | 0x{s.hex().upper():16s} | {cnt:14d} | {rule_str}")

    lines.append("")
    lines.append("--- Census Top 20 Candidates (Excluding Slots 0..2) ---")
    other_counts = {k: v for k, v in counts.items() if k not in FIXED_SLOTS}
    sorted_others = sorted(other_counts.items(), key=lambda x: (-x[1], x[0]))[:20]
    for rank, (k, cnt) in enumerate(sorted_others, start=1):
        lines.append(f"{rank:2d}. {k.decode('ascii', errors='replace')} : {cnt} Add Orders")

    lines.append("")
    lines.append("CENSUS RESULT: PASS (rtl/t2t_symbols.vh updated successfully).")

    with open(out_report, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="ITCH 5.0 Symbol Census (Section 8.1)")
    parser.add_argument("--input", type=pathlib.Path, default=None, help="Path to raw ITCH 5.0 binary file")
    parser.add_argument("--report", type=pathlib.Path, default=pathlib.Path("reports/sim/symbol_census.txt"))
    parser.add_argument("--header", type=pathlib.Path, default=pathlib.Path("rtl/t2t_symbols.vh"))
    args = parser.parse_args()

    selected, counts, fname, digest = run_census(args.input)
    write_symbols_header(selected, args.header)
    write_census_report(selected, counts, fname, digest, args.report)
    print(f"Symbol census complete. Slots 0..7: {[s.decode('ascii') for s in selected]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
